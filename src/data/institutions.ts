/** Sandbox tenants provisioned on sbqr.api that are not in Annex A. */
const SANDBOX = new Map<string, string>([['031267', 'RVL Sandbox PSP']]);

export function institutionName(type?: string, id?: string): string {
  if (!type || !id) return 'Unknown institution';
  const code = type + id;
  return DIRECTORY.get(code) ?? SANDBOX.get(code) ?? `${INSTITUTION_TYPES[type] ?? 'Institution'} ${id}`;
}
